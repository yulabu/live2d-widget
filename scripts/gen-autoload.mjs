/**
 * Generate dist/autoload.js — the one-line bootstrap used on deployed sites.
 *
 * It is generated (not hand-edited) so that dist stays in sync with
 * widget.config.json and the sources. Run with: npm run build
 */

import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

function readJson(rel) {
  return JSON.parse(fs.readFileSync(path.join(ROOT, rel), 'utf8'));
}

const config = readJson('widget.config.json');

const commitHash = (() => {
  try {
    return execSync('git rev-parse --short HEAD', { cwd: ROOT }).toString().trim();
  } catch {
    return 'unknown';
  }
})();

const banner = `/*!
 * Live2D Widget
 * https://github.com/stevenjoezhang/live2d-widget
 * Generated by scripts/gen-autoload.mjs — do not edit by hand.
 * Build: ${commitHash}
 */
`;

const template = `(function () {
  // Automatically detect base path from script URL.
  // Works both locally (e.g. /dist/) and on CDN (jsDelivr).
  var live2d_path = (function () {
    var src = document.currentScript && document.currentScript.src;
    if (!src) return './';
    return src.substring(0, src.lastIndexOf('/') + 1);
  })();
  var repoBase = (function () {
    var src = document.currentScript && document.currentScript.src;
    if (!src) return '';
    var idx = src.indexOf('/dist/');
    return idx >= 0 ? src.substring(0, idx) : '';
  })();

  // Avoid cross-origin issues with image resources.
  var OriginalImage = window.Image;
  window.Image = function () {
    var img = new OriginalImage(...arguments);
    img.crossOrigin = 'anonymous';
    return img;
  };
  window.Image.prototype = OriginalImage.prototype;

  function loadExternalResource(url, type) {
    return new Promise(function (resolve, reject) {
      var tag;
      if (type === 'css') {
        tag = document.createElement('link');
        tag.rel = 'stylesheet';
        tag.href = url;
      } else if (type === 'js') {
        tag = document.createElement('script');
        tag.type = 'module';
        tag.src = url;
      }
      if (tag) {
        tag.onload = function () { resolve(url); };
        tag.onerror = function () { reject(url); };
        document.head.appendChild(tag);
      }
    });
  }

  (async function () {
    var cubism2Path = live2d_path + '__CUBISM2_PATH__';
    var cubism5Path = '__CUBISM5_PATH__';
    await Promise.all([
      loadExternalResource(live2d_path + 'waifu.css', 'css'),
      loadExternalResource(live2d_path + 'waifu-tips.js', 'js'),
    ]);

    // Fetch waifu-tips.json and resolve model paths relative to the repo base.
    var waifuPath = live2d_path + 'waifu-tips.json';
    if (repoBase) {
      var resp = await fetch(waifuPath);
      var tips = await resp.json();
      if (tips.models) {
        tips.models.forEach(function (m) {
          m.paths = m.paths.map(function (p) {
            return p.startsWith('/') ? repoBase + p : p;
          });
        });
      }
      var blob = new Blob([JSON.stringify(tips)], { type: 'application/json' });
      waifuPath = URL.createObjectURL(blob);
    }

    window.initWidget({
      waifuPath: waifuPath,
      cubism2Path: cubism2Path,
      cubism5Path: cubism5Path,
      modelId: 0,
      tools: __TOOLS__,
      logLevel: '__LOG_LEVEL__',
      size: __SIZE__,
      drag: __DRAG__,
      showToggleAfterQuit: __SHOW_TOGGLE_AFTER_QUIT__,
      forceDefaultModel: __FORCE_DEFAULT_MODEL__,
      tapCountHide: __TAP_COUNT_HIDE__,
    });
    console.log('%c[Live2D Widget]%c build __COMMIT_HASH__', 'color:#cd3e45;font-weight:bold;', 'color:#999;');
  })();
})();
`;

const autoload = banner + template
  .replace('__CUBISM2_PATH__', config.cubism2Path)
  .replace('__CUBISM5_PATH__', config.cubism5Path)
  .replace('__TOOLS__', JSON.stringify(config.tools))
  .replace('__LOG_LEVEL__', config.logLevel)
  .replace('__SIZE__', String(config.size))
  .replace('__DRAG__', String(!!config.drag))
  .replace('__SHOW_TOGGLE_AFTER_QUIT__', String(!!config.showToggleAfterQuit))
  .replace('__FORCE_DEFAULT_MODEL__', String(!!config.forceDefaultModel))
  .replace('__TAP_COUNT_HIDE__', JSON.stringify(config.tapCountHide ?? null))
  .replace('__COMMIT_HASH__', commitHash);

const outDir = path.join(ROOT, 'dist');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'autoload.js'), autoload);
console.log('[gen-autoload] dist/autoload.js written');